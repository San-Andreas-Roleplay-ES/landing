/**
 * Nombre del skin original con ese ID (`skinName(1)` → "The Truth"), o null si
 * el ID no es de los originales (p. ej. un ID nuevo del servidor).
 *
 * Varios skins comparten nombre ("Normal Ped", "Beach Guy"…): son peds
 * genéricos del juego, no un error de la tabla.
 */
export function skinName(id: number): string | null {
  return SKINS[id]?.[1] ?? null;
}

/**
 * Nombre del modelo del juego (`skinModelName(1)` → "truth"), que es el del
 * .dff/.txd original con el que llegan muchos skins modificados.
 */
export function skinModelName(id: number): string | null {
  return SKINS[id]?.[0] ?? null;
}

export function skinGender(id: number): SkinGender | null {
  return SKINS[id]?.[2] ?? null;
}

export function skinRace(id: number): SkinRace | null {
  return SKINS[id]?.[3] ?? null;
}

/**
 * Etiqueta para la interfaz: "The Truth (1)". Para un ID que no es de los
 * originales, solo "Skin 20001".
 */
export function skinLabel(id: number): string {
  const name = skinName(id);
  return name ? `${name} (${id})` : `Skin ${id}`;
}
